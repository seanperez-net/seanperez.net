export type IconName = keyof typeof paths;

export const iconNames = Object.keys(paths) as IconName[];

/** M3 optical sizes, with e-store's names: xs 16, dense 18, sm 20, md 24 (default), lg 40, xl 48. */
export type IconSize =
  | "xs"
  | "dense"
  | "sm"
  | "md"
  | "fabMd"
  | "buttonLg"
  | "fabLg"
  | "lg"
  | "xl";

export const iconVariants = tv({
  base: ["shrink-0", "fill-current", "select-none"],
  variants: {
    size: {
      /** 16dp: dense toolbars. */
      xs: ["size-4"],
      /** 18dp: M3 chips and segmented buttons. */
      dense: ["size-4.5"],
      /** 20dp: M3 extra-small and small buttons, Expressive menus. */
      sm: ["size-5"],
      /** 24dp: the standard size. */
      md: ["size-6"],
      /** 32dp: M3 large button and large icon button (e-store's `--text-icon-button-lg`). */
      buttonLg: ["size-8"],
      /** 28dp: M3 medium FAB and medium extended FAB (material-web `fab-medium` icon size). */
      fabMd: ["size-7"],
      /** 36dp: M3 large FAB and large extended FAB (material-web `fab-large`; e-store's `--text-icon-fab-lg`). */
      fabLg: ["size-9"],
      /** 40dp: emphasis; M3 extra-large button. */
      lg: ["size-10"],
      /** 48dp: hero and display. */
      xl: ["size-12"],
    },
  },
  defaultVariants: { size: "md" },
});

export type IconProps = Omit<PropsOf<"svg">, "children"> & {
  /** Material Symbol name. Only the names in `paths` exist. */
  name: IconName;
  /** M3 optical size: xs 16, dense 18, sm 20, md 24 (default), lg 40, xl 48. */
  size?: IconSize;
  /**
   * Accessible name, for an icon that carries meaning no nearby text gives (a status, a rating).
   * With it the icon is `role="img"` named by this text. Without it the icon is decorative and
   * `aria-hidden`: the control around it carries the name.
   */
  label?: string;
};

/**
 * e-store's `Icon` API (`size`, `label`, `data-qds-icon`) on inline SVG paths instead of the
 * Material Symbols font. Decorative by default.
 */
export const Icon = component$<IconProps>(
  ({ name, size, label, class: className, ...rest }) => {
    const a11y = label
      ? { role: "img" as const, "aria-label": label }
      : { "aria-hidden": "true" as const };
    return (
      <svg
        {...rest}
        data-qds-icon=""
        viewBox="0 -960 960 960"
        {...a11y}
        class={[iconVariants({ size }), className]}
      >
        <path d={paths[name]} />
      </svg>
    );
  },
);
